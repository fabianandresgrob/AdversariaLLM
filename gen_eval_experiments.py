"""Write jsc-jobs experiment files that evaluate every finished coop checkpoint, one file per
(eval type, block), following the eval layout:

    checkpoints_coop/<block>/<run>/threshold_1pct.json        calibration (next to the probe, where
                                                               defense=coop_probe looks for it)
    outputs/eval/overrefusal/<block>/<run>/                    over-refusal (string match + judge)
    outputs/eval/overrefusal/reference/base/                   same eval on the un-adapted base model

Usage (from the repo root, after training):
    pixi run --frozen python gen_eval_experiments.py checkpoints_coop/*/*
    pixi run --frozen jobs submit eval-calib-A-eps-sweep --dry-run

Each run gets `+block=<block> +run=<run>`; the eval configs build their paths from those via
${block}/${run} interpolation, so the scripts themselves need no single-checkpoint mode.
"""

import argparse
import sys
from collections import defaultdict
from pathlib import Path

import yaml

from gen_coop_models import is_checkpoint

REPO = Path(__file__).resolve().parent
CKPT = "${root_dir}/checkpoints_coop/${block}/${run}"

CALIB = {
    "entrypoint": "run_calibrate_probe.py",
    "name": "calib-{+run}",
    "time_per_run": "00:30:00",
    "overrides": {
        "adapter_path": CKPT + "/final_adapter",
        "checkpoint_path": CKPT + "/final_reader.pt",
    },
    "artifacts": ["checkpoints_coop/{+block}/{+run}/threshold_1pct.json"],
}
OVERREFUSAL = {
    "entrypoint": "run_overrefusal_eval.py",
    "name": "overrefusal-{+run}",
    "time_per_run": "02:00:00",
    "overrides": {
        "~checkpoints.base": "base",
        "+checkpoints.model": CKPT + "/final_adapter",
        "out": "${root_dir}/outputs/eval/overrefusal/${block}/${run}",
        "judge.enabled": True,
    },
    "artifacts": ["outputs/eval/overrefusal/{+block}/{+run}/overrefusal.json"],
}
OVERREFUSAL_REFERENCE = {
    "entrypoint": "run_overrefusal_eval.py",
    "name": "overrefusal-base",
    "time_per_run": "02:00:00",
    "overrides": {
        "out": "${root_dir}/outputs/eval/overrefusal/reference/base",
        "judge.enabled": True,
    },
    "artifacts": ["outputs/eval/overrefusal/reference/base/overrefusal.json"],
}
HEADER = "# GENERATED by gen_eval_experiments.py from the finished checkpoints -- regenerate, don't edit.\n"


def experiment(template: dict, block: str, runs: list[str]) -> dict:
    spec = {k: (dict(v) if isinstance(v, dict) else v) for k, v in template.items()}
    spec["overrides"] = {"+block": block, **spec["overrides"]}
    spec["sweep"] = {"+run": sorted(runs)}
    return spec


def build(paths: list[Path], repo: Path) -> dict[str, dict]:
    blocks = defaultdict(list)
    for path in paths:
        if is_checkpoint(path):
            rel = path.resolve().relative_to((repo / "checkpoints_coop").resolve())
            blocks[rel.parent.as_posix()].append(rel.name)
    files = {}
    for block, runs in sorted(blocks.items()):
        files[f"eval-calib-{block}.yaml"] = experiment(CALIB, block, runs)
        files[f"eval-overrefusal-{block}.yaml"] = experiment(OVERREFUSAL, block, runs)
    if blocks:
        files["eval-overrefusal-reference.yaml"] = OVERREFUSAL_REFERENCE
    return files


def main(argv=None, repo: Path = REPO) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("paths", nargs="+", type=Path, help="checkpoint directories (globs expanded by the shell)")
    parser.add_argument("--dry-run", action="store_true", help="list the files instead of writing them")
    args = parser.parse_args(argv)

    files = build(args.paths, repo)
    out_dir = repo / "experiments"
    for name, spec in files.items():
        if args.dry_run:
            runs = spec.get("sweep", {}).get("+run", [spec["name"]])
            print(f"{name}: {len(runs)} run(s)")
        else:
            (out_dir / name).write_text(HEADER + yaml.safe_dump(spec, sort_keys=False, default_flow_style=False))
    print(f"{len(files)} experiment file(s) {'would be ' if args.dry_run else ''}written to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
