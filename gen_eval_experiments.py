"""Write jsc-jobs experiment files that evaluate finished checkpoints, one file per (eval type, block),
following the eval layout:

    checkpoints_coop/<block>/<run>/threshold_1pct_calib.json  calibration on alpaca[700:2700] (next to the probe, where
                                                               defense=coop_probe looks for it) -- coop only
    outputs/eval/overrefusal/<block>/<run>/                    over-refusal (string match + judge)
    outputs/eval/utility/<block>/<run>/                        lm_eval MMLU/ARC-C/GSM8K (+ per-sample generations)
    outputs/eval/cross_attack/<block>/<run>/seed<k>/           cross-attack eval (opt-in via --cross-attack) -- coop only
    outputs/eval/{overrefusal,utility}/reference/base/         same evals on the un-adapted base model

Usage (from the repo root, after training):
    pixi run --frozen python gen_eval_experiments.py checkpoints_coop/*/* checkpoints_cat/*/*
    pixi run --frozen python gen_eval_experiments.py checkpoints_coop/*/* \\
        --cross-attack 'A-eps-sweep:A-eps0.05-*' E-adaptive
    pixi run --frozen jobs submit eval-calib-A-eps-sweep --dry-run

Coop checkpoints (checkpoints_coop/, final_adapter + final_reader.pt + run_config.json) get calibration,
over-refusal and utility. CAT checkpoints (checkpoints_cat/, final_adapter only -- no probe) get over-refusal
and utility. Each run gets `+block=<block> +run=<run>`; the eval configs build their paths from those via
${block}/${run} interpolation.
"""

import argparse
import fnmatch
import sys
from collections import defaultdict
from pathlib import Path

import yaml

from gen_coop_models import is_checkpoint

REPO = Path(__file__).resolve().parent
ROOTS = {"coop": "checkpoints_coop", "cat": "checkpoints_cat"}
HEADER = "# GENERATED by gen_eval_experiments.py from the finished checkpoints -- regenerate, don't edit.\n"
CROSS_ATTACK_SEEDS = [0, 1, 2]


def _ckpt(kind: str) -> str:
    return "${root_dir}/" + ROOTS[kind] + "/${block}/${run}"


def calib(kind: str) -> dict:
    return {
        "entrypoint": "run_calibrate_probe.py",
        "name": "calib-{+run}",
        "time_per_run": "00:30:00",
        "overrides": {
            "adapter_path": _ckpt(kind) + "/final_adapter",
            "checkpoint_path": _ckpt(kind) + "/final_reader.pt",
            "calibration_window": "calib",
        },
        "artifacts": [ROOTS[kind] + "/{+block}/{+run}/threshold_1pct_calib.json"],
    }


def overrefusal(kind: str) -> dict:
    return {
        "entrypoint": "run_overrefusal_eval.py",
        "name": "overrefusal-{+run}",
        "time_per_run": "02:00:00",
        "overrides": {
            "~checkpoints.base": "base",
            "+checkpoints.model": _ckpt(kind) + "/final_adapter",
            "out": "${root_dir}/outputs/eval/overrefusal/${block}/${run}",
            "judge.enabled": True,
        },
        "artifacts": ["outputs/eval/overrefusal/{+block}/{+run}/overrefusal.json"],
    }


def utility(kind: str) -> dict:
    return {
        "entrypoint": "run_utility_eval.py",
        "name": "utility-{+run}",
        "time_per_run": "02:00:00",
        "overrides": {
            "adapter_path": _ckpt(kind) + "/final_adapter",
            "out": "${root_dir}/outputs/eval/utility/${block}/${run}",
        },
        "artifacts": ["outputs/eval/utility/{+block}/{+run}/utility.json"],
    }


def cross_attack(kind: str) -> dict:
    """Tier K: attack each checkpoint under model-only AND detector-aware attacks (4 detector coeffs), several
    attack seeds, so 'trained adaptively' and 'attacked adaptively' can be separated."""
    return {
        "entrypoint": "run_cross_attack_eval.py",
        "name": "xattack-{+run}-a{seed}",
        "time_per_run": "02:00:00",
        "overrides": {
            "adapter_path": _ckpt(kind) + "/final_adapter",
            "eval_use_detector": [False, True],
            "out": "${root_dir}/outputs/eval/cross_attack/${block}/${run}/seed${seed}",
        },
        "artifacts": ["outputs/eval/cross_attack/{+block}/{+run}/seed{seed}/cross_attack_eval.json"],
    }


OVERREFUSAL_REFERENCE = {
    "entrypoint": "run_overrefusal_eval.py",
    "name": "overrefusal-base",
    "time_per_run": "02:00:00",
    "overrides": {"out": "${root_dir}/outputs/eval/overrefusal/reference/base", "judge.enabled": True},
    "artifacts": ["outputs/eval/overrefusal/reference/base/overrefusal.json"],
}
UTILITY_REFERENCE = {
    "entrypoint": "run_utility_eval.py",
    "name": "utility-base",
    "time_per_run": "02:00:00",
    "overrides": {"out": "${root_dir}/outputs/eval/utility/reference/base"},
    "artifacts": ["outputs/eval/utility/reference/base/utility.json"],
}


def experiment(template: dict, block: str, runs: list[str], extra_sweep: dict | None = None) -> dict:
    spec = {k: (dict(v) if isinstance(v, dict) else v) for k, v in template.items()}
    spec["overrides"] = {"+block": block, **spec["overrides"]}
    spec["sweep"] = {"+run": sorted(runs), **(extra_sweep or {})}
    return spec


def checkpoint_kind(path: Path, repo: Path) -> tuple[str, str, str] | None:
    """(kind, block, run) for a finished checkpoint dir, else None."""
    resolved = path.resolve()
    for kind, root in ROOTS.items():
        try:
            rel = resolved.relative_to((repo / root).resolve())
        except ValueError:
            continue
        if len(rel.parts) != 2:
            return None
        finished = is_checkpoint(path) if kind == "coop" else (path / "final_adapter").is_dir()
        return (kind, rel.parts[0], rel.parts[1]) if finished else None
    return None


def parse_cross_attack(specs: list[str]) -> dict[str, str]:
    """'BLOCK' or 'BLOCK:RUN_GLOB' -> {block: glob}."""
    out = {}
    for s in specs:
        block, _, pattern = s.partition(":")
        out[block] = pattern or "*"
    return out


def build(paths: list[Path], repo: Path, cross_attack_specs: list[str] | None = None) -> dict[str, dict]:
    blocks: dict[tuple[str, str], list[str]] = defaultdict(list)
    for path in paths:
        found = checkpoint_kind(path, repo)
        if found:
            kind, block, run = found
            blocks[(kind, block)].append(run)
    cross = parse_cross_attack(cross_attack_specs or [])
    files = {}
    for (kind, block), runs in sorted(blocks.items()):
        if kind == "coop":
            files[f"eval-calib-{block}.yaml"] = experiment(calib(kind), block, runs)
        files[f"eval-overrefusal-{block}.yaml"] = experiment(overrefusal(kind), block, runs)
        files[f"eval-utility-{block}.yaml"] = experiment(utility(kind), block, runs)
        if kind == "coop" and block in cross:
            selected = [r for r in runs if fnmatch.fnmatchcase(r, cross[block])]
            if not selected:
                raise ValueError(f"--cross-attack {block}:{cross[block]} matches no finished run")
            files[f"eval-crossattack-{block}.yaml"] = experiment(
                cross_attack(kind), block, selected, {"seed": CROSS_ATTACK_SEEDS})
    unknown = sorted(set(cross) - {b for k, b in blocks if k == "coop"})
    if unknown:
        raise ValueError(f"--cross-attack blocks without finished coop checkpoints: {unknown}")
    if blocks:
        files["eval-overrefusal-reference.yaml"] = OVERREFUSAL_REFERENCE
        files["eval-utility-reference.yaml"] = UTILITY_REFERENCE
    return files


def main(argv=None, repo: Path = REPO) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("paths", nargs="+", type=Path, help="checkpoint directories (globs expanded by the shell)")
    parser.add_argument("--cross-attack", nargs="*", default=[], metavar="BLOCK[:RUN_GLOB]",
                        help="also write cross-attack eval experiments for these coop blocks/runs")
    parser.add_argument("--dry-run", action="store_true", help="list the files instead of writing them")
    args = parser.parse_args(argv)

    files = build(args.paths, repo, args.cross_attack)
    out_dir = repo / "experiments"
    for name, spec in files.items():
        if args.dry_run:
            sweep = spec.get("sweep", {})
            n = len(sweep.get("+run", [spec["name"]])) * len(sweep.get("seed", [None]))
            print(f"{name}: {n} run(s)")
        else:
            (out_dir / name).write_text(HEADER + yaml.safe_dump(spec, sort_keys=False, default_flow_style=False))
    print(f"{len(files)} experiment file(s) {'would be ' if args.dry_run else ''}written to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
