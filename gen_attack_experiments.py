"""Write jsc-jobs experiment files for the transfer attacks on a chosen set of checkpoints.

One file per (attack, shard): each run attacks a slice of the behavior set with one model, so a
100-behavior GCG run (~7 min/behavior) splits across GPUs instead of occupying one for 12 hours.
Models are named by their conf/models/models.yaml entry (gen_coop_models.py writes those for coop
checkpoints; CAT entries are hand-written), and results land in the run's own hydra output dir,
tracked by the file DB the run_attacks.py profile already configures.

    pixi run --frozen python gen_attack_experiments.py --attacks gcg inpainting --dry-run
    pixi run --frozen python gen_attack_experiments.py --attacks gcg --shards 4
    pixi run --frozen jobs submit attack-gcg-shard0 --dry-run

Defaults attack the eight-model selection from round 2. `--defense coop_probe` runs the attack
against the full pipeline instead of the raw model; GCG is meant to be run undefended and then
replayed (attack=replay, source=<the GCG results dir>), which is a separate, cheap submission.

`gcg_adaptive` is detector-aware GCG: the suffix is optimised to elicit the target AND to read
benign at the coop probe. Its probe path is filled in per swept model automatically. Neither GCG
can run against a runtime defense (they need gradients; the defense only filters output -- see
defenses.registry.DEFENSE_COMPATIBLE_ATTACKS), so the pipeline numbers come from replaying them:

    gcg          defense=none  ->  replay defense=coop_probe    # what the probe catches
    gcg_adaptive defense=none  ->  replay defense=coop_probe    # what it catches when evaded

Drop models with no probe (the base model) from --models when using gcg_adaptive.
"""

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent
HEADER = "# GENERATED by gen_attack_experiments.py -- regenerate, don't edit.\n"
MODELS = [  # models.yaml entry names; see the round-2 selection
    "base-llama31-8b",  # undefended reference (alias entry; run names may not contain "/")
    "A-eps0p05-s0",   # model-only trained (Stage B)
    "E-nd6-s0",       # detector-aware, 6 detector steps -- best coop model
    "I-full-s0",      # full recipe
    "I-lrep0-s0",     # lambda_rep = 0 ablation
    "L-cold-s0",      # cold-started probe
    "J-ul-away1p0-s0",  # CAT baseline (ul)
    "J-ce-away1p0-s0",  # CAT baseline (ce)
]
BEHAVIORS = 100
# Per-behavior generation budget for the attacks that sample rather than optimise. 1024 inpainting
# variants is far past the point where the budget curve flattens; 128 is the agreed protocol and
# cuts the run 8x. PAIR's own budget is 30 streams x 3 steps = 90 queries, already under it.
INPAINTING_SAMPLES = 128
TIME_PER_RUN = {"gcg": "06:00:00", "gcg_adaptive": "06:00:00", "inpainting": "03:00:00",
                "pair": "06:00:00", "direct": "01:00:00", "replay": "01:00:00"}
# PAIR aborts a whole run when its attacker returns unparseable JSON max_attempts times in a row; the
# default 10 loses roughly one run in eight. Retrying more costs seconds and changes no attack semantics.
EXTRA_OVERRIDES = {
    "pair": {
        "attacks.pair.attack_model.max_attempts": 30,
        # Judge with the attacker rather than the default (judge_model.id=null => the target judges
        # itself). Self-judging makes the attacker's feedback incomparable across arms -- measured on
        # the 100-behavior runs, the share of responses rated >=8 ranged from 2.3% (base) to 64.9%
        # (J-ce) -- and a safety-trained target sometimes refuses to rate at all. vicuna is already
        # loaded as the attacker and is not safety-tuned, so this costs no extra VRAM (see
        # pair.select_judge) and no extra refusals.
        "attacks.pair.judge_model.id": "lmsys/vicuna-13b-v1.5",
        "attacks.pair.judge_model.tokenizer_id": "lmsys/vicuna-13b-v1.5",
    },
    "inpainting": {"attacks.inpainting.num_samples_per_behavior": INPAINTING_SAMPLES},
}
# gcg_adaptive needs no probe override: conf/attacks/attacks.yaml resolves the swept model's own
# reader_path. Passing it on the CLI does not work -- hydra cannot parse a nested interpolation
# bare, and quoting it leaves the quotes inside the value, so the path fails to open.


def shard_bounds(n_behaviors: int, shards: int) -> list[tuple[int, int]]:
    step = -(-n_behaviors // shards)
    return [(start, min(start + step, n_behaviors)) for start in range(0, n_behaviors, step)]


def experiment(attack: str, models: list[str], start: int, stop: int, defense: str | None) -> dict:
    overrides = {
        "attack": attack,
        "dataset": "jbb_behaviors",
        "datasets.jbb_behaviors.idx": f"list(range({start},{stop}))",
    }
    overrides.update(EXTRA_OVERRIDES.get(attack, {}))
    if defense:
        overrides["defense"] = defense
    return {
        "entrypoint": "run_attacks.py",
        # The behavior WINDOW, not the shard index: "b0" alone meant 0-24 in the 100-behavior
        # batch and 0-19 in the 20-behavior one, so the same run name described two protocols and
        # the second submission was silently skipped as an already-existing run.
        "name": f"{attack}-{{model}}-b{start}-{stop}",
        "time_per_run": TIME_PER_RUN.get(attack, "06:00:00"),
        "overrides": overrides,
        "sweep": {"model": models},
    }


# Attacks that can run against a runtime defense, mirroring
# adversariallm.defenses.registry.DEFENSE_COMPATIBLE_ATTACKS. Optimisation attacks are absent:
# they need gradients the defended pipeline does not expose. Checked here so an incompatible
# combination fails at generation time, not after the jobs have been submitted and started.
DEFENSE_COMPATIBLE = frozenset({"actor", "ample_gcg", "bon", "crescendo", "direct", "human_jailbreaks",
                                "inpainting", "jailbreak_r1", "pair", "replay"})


def build(attacks: list[str], models: list[str], shards: int, n_behaviors: int,
          defense: str | None) -> dict[str, dict]:
    if defense:
        bad = sorted(set(attacks) - DEFENSE_COMPATIBLE)
        if bad:
            raise ValueError(
                f"{bad} cannot run against defense={defense!r}: they need gradients the defended "
                f"pipeline does not expose. Run them with defense=none and replay the result "
                f"(attack=replay defense={defense})."
            )
    files = {}
    for attack in attacks:
        for index, (start, stop) in enumerate(shard_bounds(n_behaviors, shards)):
            suffix = f"-{defense}" if defense else ""
            del index  # the window names the file; a shard index would repeat across protocols
            files[f"attack-{attack}{suffix}-b{start}-{stop}.yaml"] = experiment(
                attack, models, start, stop, defense)
    return files


def main(argv=None, repo: Path = REPO) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--attacks", nargs="+", default=["gcg"], help="attack names from conf/attacks/attacks.yaml")
    parser.add_argument("--models", nargs="+", default=MODELS, help="models.yaml entry names")
    parser.add_argument("--shards", type=int, default=4, help="split the behavior set into this many runs")
    parser.add_argument("--behaviors", type=int, default=BEHAVIORS, help="how many behaviors to attack")
    parser.add_argument("--defense", default=None, help="run against a defense (e.g. coop_probe) instead of the raw model")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    files = build(args.attacks, args.models, args.shards, args.behaviors, args.defense)
    out_dir = repo / "experiments"
    for name, spec in files.items():
        if args.dry_run:
            print(f"{name}: {len(spec['sweep']['model'])} run(s), {spec['overrides']['datasets.jbb_behaviors.idx']}")
        else:
            (out_dir / name).write_text(HEADER + yaml.safe_dump(spec, sort_keys=False, default_flow_style=False))
    total = sum(len(s["sweep"]["model"]) for s in files.values())
    print(f"{len(files)} experiment file(s), {total} run(s) {'would be ' if args.dry_run else ''}written to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
